export function findStaticTranslation(text: string, targetLang: string): string | null {
  if (!text) return null;
  const trimmed = text.trim();
  const direct = STATIC_DICTIONARY[trimmed];
  if (direct) {
    return targetLang === "es" ? direct.es : direct.en;
  }
  const lower = trimmed.toLowerCase();
  for (const [key, entry] of Object.entries(STATIC_DICTIONARY)) {
    if (key.toLowerCase() === lower) {
      return targetLang === "es" ? entry.es : entry.en;
    }
    if (entry.es.toLowerCase() === lower) {
      return targetLang === "es" ? entry.es : entry.en;
    }
  }
  return null;
}
